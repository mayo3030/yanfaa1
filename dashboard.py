        def run_async_in_thread(coro):
            """Run async code in a separate thread with proper Windows event loop"""
            import threading
            result = [None, None]
            
            def thread_target():
                # Create new event loop for this thread
                if sys.platform == 'win32':
                    # Use ProactorEventLoop for Windows (required for Playwright subprocess)
                    loop = asyncio.ProactorEventLoop()
                else:
                    loop = asyncio.new_event_loop()
                asyncio.set_event_loop(loop)
                try:
                    result[0] = loop.run_until_complete(coro)
                except Exception as e:
                    result[1] = e
                finally:
                    loop.close()
            
            thread = threading.Thread(target=thread_target)
            thread.start()
            thread.join()
            
            if result[1]:
                raise result[1]
            return result[0]
        
