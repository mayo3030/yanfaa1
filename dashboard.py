class CookieConverter:
    """Cookie format converter"""
    
    def json_to_netscape(self, cookies: Dict, domain: str = "") -> str:
        """Convert cookies from JSON to Netscape format"""
        lines = [
            "# Netscape HTTP Cookie File",
            "# Generated by Yanfaa Professional Scraper",
            f"# Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
            ""
        ]
        
        if domain:
            parsed = urlparse(domain)
            domain = parsed.netloc or parsed.path
            if domain.startswith('www.'):
                domain = domain[4:]
        
        expiration = "2147483647"
        
        if isinstance(cookies, dict):
            for name, value in cookies.items():
                if isinstance(value, dict):
                    cookie_domain = value.get('domain', domain)
                    cookie_path = value.get('path', '/')
                    cookie_secure = "TRUE" if value.get('secure', False) else "FALSE"
                    cookie_expiration = str(value.get('expiration', expiration))
                    cookie_name = value.get('name', name)
                    cookie_value = value.get('value', str(value))
                else:
                    cookie_domain = f".{domain}" if domain else ""
                    cookie_path = "/"
                    cookie_secure = "FALSE"
                    cookie_expiration = expiration
                    cookie_name = name
                    cookie_value = str(value)
                
                line = f"{cookie_domain}\tTRUE\t{cookie_path}\t{cookie_secure}\t{cookie_expiration}\t{cookie_name}\t{cookie_value}"
                lines.append(line)
        
        return "\n".join(lines)
    
    def netscape_to_json(self, netscape_content: str) -> Dict:
        """Convert cookies from Netscape to JSON format"""
        cookies = {}
        lines = netscape_content.split('\n')
        
        for line in lines:
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            
            parts = line.split('\t')
            if len(parts) >= 7:
                domain, flag, path, secure, expiration, name, value = parts[:7]
                cookies[name] = {
                    "domain": domain,
                    "path": path,
                    "secure": secure.lower() == "true",
                    "expiration": int(expiration) if expiration.isdigit() else None,
                    "value": value
                }
        
        return cookies

