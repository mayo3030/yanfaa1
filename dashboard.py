class CredentialsManager:
    """Manage credentials"""
    
    def __init__(self, credentials_file: str = None):
        self.credentials_file = Path(credentials_file) if credentials_file else config.BASE_DIR / "credentials.json"
        self.credentials: Dict = {}
        self.load_credentials()
    
    def load_credentials(self):
        """Load credentials from file"""
        try:
            if self.credentials_file.exists():
                with open(self.credentials_file, 'r', encoding='utf-8') as f:
                    self.credentials = json.load(f)
            else:
                self.credentials = {}
        except Exception as e:
            print(f"Error loading credentials: {str(e)}")
            self.credentials = {}
    
    def save_credentials(self):
        """Save credentials to file"""
        try:
            with open(self.credentials_file, 'w', encoding='utf-8') as f:
                json.dump(self.credentials, f, indent=2, ensure_ascii=False)
            return True
        except Exception as e:
            print(f"Error saving credentials: {str(e)}")
            return False
    
    def add_credential(self, name: str, username: str, password: str, 
                      base_url: str = "", login_url: str = ""):
        """Add new credential"""
        if name in self.credentials:
            raise ValueError(f"Credential '{name}' already exists")
        
        self.credentials[name] = {
            "name": name,
            "username": username,
            "email": username,
            "password": password,
            "base_url": base_url,
            "login_url": login_url,
            "created_at": datetime.now().isoformat()
        }
        return self.save_credentials()
    
    def get_credential(self, name: str) -> Optional[Dict]:
        """Get specific credential"""
        return self.credentials.get(name)
    
    def get_all_credentials(self) -> List[Dict]:
        """Get all credentials"""
        return list(self.credentials.values())
    
    def delete_credential(self, name: str) -> bool:
        """Delete credential"""
        if name in self.credentials:
            del self.credentials[name]
            return self.save_credentials()
        return False

