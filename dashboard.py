        def download_videos_sync(course_slug, output_dir):
            """Download course videos using yt-dlp"""
            import subprocess
            import re
            
            downloaded = []
            errors = []
            
            output_path = Path(output_dir)
            output_path.mkdir(parents=True, exist_ok=True)
            
            # Create Netscape cookies file for yt-dlp
            netscape_cookies_file = output_path / "cookies.txt"
            try:
                with open(cookies_file, 'r', encoding='utf-8') as f:
                    cookies_data = json.load(f)
                
                with open(netscape_cookies_file, 'w', encoding='utf-8') as f:
                    f.write("# Netscape HTTP Cookie File\n")
                    f.write("# https://curl.haxx.se/rfc/cookie_spec.html\n")
                    f.write("# This is a generated file! Do not edit.\n\n")
                    
                    for name, data in cookies_data.items():
                        if isinstance(data, dict):
                            domain = data.get('domain', '.yanfaa.com')
                            path = data.get('path', '/')
                            secure = 'TRUE' if data.get('secure', False) else 'FALSE'
                            expiry = str(int(data.get('expiration', 0)))
                            value = data.get('value', '')
                        else:
                            domain = '.yanfaa.com'
                            path = '/'
                            secure = 'FALSE'
                            expiry = '0'
                            value = str(data)
                        
                        # Netscape format: domain\tflag\tpath\tsecure\texpiry\tname\tvalue
                        flag = 'TRUE' if domain.startswith('.') else 'FALSE'
                        f.write(f"{domain}\t{flag}\t{path}\t{secure}\t{expiry}\t{name}\t{value}\n")
                
                print(f"🍪 Created Netscape cookies file: {netscape_cookies_file}")
            except Exception as e:
                print(f"⚠️ Cookie file warning: {str(e)}")
            
            # Course URL
            course_url = f"https://yanfaa.com/us/single/{course_slug}"
            
            # yt-dlp command (using python -m for Windows compatibility)
            cmd = [
                sys.executable, '-m', 'yt_dlp',
                '--cookies', str(netscape_cookies_file),
                '-o', str(output_path / '%(title)s.%(ext)s'),
                '--write-subs',
                '--sub-langs', 'all',
                '--embed-subs',
                '--no-check-certificate',
                '--user-agent', 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36',
                course_url
            ]
            
            print(f"🎬 Starting video download: {course_url}")
            print(f"📁 Output: {output_path}")
            
            try:
                # Run yt-dlp
                result = subprocess.run(
                    cmd,
                    capture_output=True,
                    text=True,
                    timeout=600  # 10 minute timeout
                )
                
                if result.returncode == 0:
                    print(f"✅ Video download completed!")
                    # Find downloaded files
                    for f in output_path.glob('*.mp4'):
                        downloaded.append(str(f))
                    for f in output_path.glob('*.mkv'):
                        downloaded.append(str(f))
                    for f in output_path.glob('*.webm'):
                        downloaded.append(str(f))
                else:
                    error_msg = result.stderr[:500] if result.stderr else "Unknown error"
                    print(f"❌ yt-dlp error: {error_msg}")
                    errors.append(error_msg)
                    
            except subprocess.TimeoutExpired:
                errors.append("Download timed out after 10 minutes")
                print("❌ Download timed out")
            except FileNotFoundError:
                errors.append("yt-dlp not found. Install it with: pip install yt-dlp")
                print("❌ yt-dlp not found")
            except Exception as e:
                errors.append(str(e))
                print(f"❌ Error: {str(e)}")
            
            return downloaded, errors
        
